// Pure emit planning: no node:fs, no clock, no randomness. Same input, same plan.
import type { SceneJson } from '../../template/runtime/scene';
import type { SvgFile } from '../convert/convertModel';
import type { TranslatedClass } from '../translate/planTranslate';
import { canonicalClassPath, parseQualifiedName, relativeSpecifier } from '../convert/qualifiedName';
import type { QualifiedName } from '../convert/qualifiedName';
import { buildBindings, planClassPaths, resolveImportLines } from './classPaths';
import type { ClassPathEntry } from './classPaths';
import { buildPackageJson } from './packageJson';

export interface TemplateFile {
  path: string; // posix, relative to the template root
  content: string;
}
export interface HandwrittenClass {
  className: string;
  fileName: string; // e.g. "LeftButton.ts"
  source: string;
}
export interface EmittedFile {
  path: string; // posix, relative to the output root
  content: string;
}
export interface EmitInput {
  scene: SceneJson;
  sceneJson: string; // canonical text of scene.json
  templates: TemplateFile[];
  /** Emitted translated classes (the emit closure). */
  translated: readonly TranslatedClass[];
  /** Override_Directory contents: an override replaces the translated text of the same class. */
  handwritten: HandwrittenClass[];
}

/** A class file in the plan, as the omission decision needs it. */
export interface PlannedClass {
  className: string;
  path: string; // posix, relative to the output root
  handwritten: boolean;
}

export interface PlanEmitResult {
  files: EmittedFile[];
  warnings: string[];
  classes: PlannedClass[]; // sorted by className
  /** Chosen path of every class file, sorted by className. */
  classPaths: ClassPathEntry[];
}

const CLASSES_PATH = 'src/classes.ts';
const PACKAGE_PATH = 'package.json';

function byCodeUnit(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function lf(text: string): string {
  return text.replace(/\r\n?/g, '\n');
}

/** Class names linked in the Symbol_Table, sorted and de-duplicated. */
function linkedClassNames(scene: SceneJson): Set<string> {
  const names = new Set<string>();
  for (const key of Object.keys(scene.symbols)) {
    const symbol = scene.symbols[key];
    if (symbol.type === 'sprite' && symbol.className !== undefined) names.add(symbol.className);
  }
  return names;
}

/**
 * Registry source: exactly the Scene_JSON-linked names found in classNames and not in omitted,
 * sorted by code unit. An omitted class has no import and no entry.
 */
export function buildClassesTs(
  scene: SceneJson,
  classNames: readonly string[],
  omitted: ReadonlySet<QualifiedName> = new Set(),
  chosen: ReadonlyMap<string, string> = new Map(),
): string {
  const linked = linkedClassNames(scene);
  const used = [...new Set(classNames)].filter((n) => linked.has(n) && !omitted.has(n)).sort(byCodeUnit);
  const lines: string[] = [
    '// Generated by swf-resurrect. Maps linked class names to translated classes.',
    '// Symbols without an entry run as a plain MovieClip.',
  ];
  const bindings = buildBindings(used);
  for (const n of used) {
    const { simple } = parseQualifiedName(n);
    const binding = bindings.get(n) as string;
    const spec = relativeSpecifier(CLASSES_PATH, chosen.get(n) ?? canonicalClassPath(n));
    lines.push(`import { ${binding === simple ? simple : `${simple} as ${binding}`} } from '${spec}';`);
  }
  if (used.length === 0) {
    lines.push('export const classRegistry: Record<string, never> = {};');
  } else {
    lines.push('', 'export const classRegistry = {');
    for (const n of used) lines.push(`  ${JSON.stringify(n)}: ${bindings.get(n)},`);
    lines.push('};');
  }
  return lines.join('\n') + '\n';
}

export function planEmitDetailed(
  input: EmitInput,
  svgContents: SvgFile[],
  omitted: ReadonlySet<QualifiedName> = new Set(),
): PlanEmitResult {
  const files = new Map<string, string>();
  const warnings: string[] = [];

  for (const t of input.templates) {
    const name = t.path.split('/').pop() ?? t.path;
    if (name === '.gitkeep') continue;
    if (t.path === CLASSES_PATH || t.path === PACKAGE_PATH) continue; // generated below
    files.set(t.path, lf(t.content));
  }

  const linked = linkedClassNames(input.scene);
  const sources = new Map<string, string>(); // class name -> source text
  const overridden = new Set<string>();
  for (const c of input.translated) sources.set(c.className, c.text);
  const overrides = [...input.handwritten].sort((a, b) => byCodeUnit(a.className, b.className));
  for (const h of overrides) {
    if (linked.has(h.className) || sources.has(h.className)) {
      sources.set(h.className, h.source);
      overridden.add(h.className);
    }
    else warnings.push(`Override ${h.fileName} ignored: ${h.className} is not a linked or emitted class`);
  }

  const names = [...sources.keys()].sort(byCodeUnit);

  files.set(PACKAGE_PATH, buildPackageJson());
  files.set('assets/scene.json', lf(input.sceneJson));
  for (const svg of svgContents) files.set(`assets/${svg.fileName}`, lf(svg.content));

  // Class paths: every other planned file is reserved, so a class never takes its name.
  const choices = planClassPaths(names, [...files.keys(), CLASSES_PATH]);
  const chosen = new Map(choices.map((c) => [c.className, c.path]));
  const translatedBy = new Map(input.translated.map((c) => [c.className, c]));
  for (const n of names) {
    const path = chosen.get(n) as string;
    const t = translatedBy.get(n);
    const text = lf(sources.get(n) as string);
    // Only translated text carries recorded import lines; an override is written as it is.
    files.set(path, t !== undefined && !overridden.has(n) ? resolveImportLines(text, t.importRecords, path, chosen) : text);
  }
  files.set(CLASSES_PATH, buildClassesTs(input.scene, names, omitted, chosen));

  return {
    files: [...files.keys()].sort(byCodeUnit).map((path) => ({ path, content: files.get(path) as string })),
    warnings,
    classes: names.map((n) => ({ className: n, path: chosen.get(n) as string, handwritten: overridden.has(n) })),
    classPaths: choices.map((c) => ({ className: c.className, originalPath: c.originalPath, path: c.path })),
  };
}

export function planEmit(input: EmitInput, svgContents: SvgFile[]): EmittedFile[] {
  return planEmitDetailed(input, svgContents).files;
}