/**
 * Renders the Shim stub classes from the Flash_API_Table (robustness design, "Flash_API_Table and stubs",
 * "Mechanism"). Pure: no node:*. `scripts/gen-api-stubs.ts` writes the files; a test compares the committed
 * files with this output, so the table stays the single source.
 *
 * Every member body is `stubCall('<Class>.<member>', neutral)` (template/shim/stubSupport.ts). The neutral
 * values and event rules are chosen by us (see flashApiTable.ts); nothing here was read in Ruffle.
 */
import { FLASH_API_TABLE, type FlashApiEntry, type MemberSig, type Neutral, type ParamSig } from './flashApiTable';

export const STUB_HEADER = '// Generated by "npm run gen:api-stubs" from src/translate/flashApiTable.ts. Do not edit.';

export interface RenderedStub {
  /** Class (or function) name, also the file stem. */
  name: string;
  /** Path below template/shim/stubs/. */
  file: string;
  text: string;
}

/** What each No_Event class does not dispatch, for the `api-stub-no-event:<Class>` detail. */
const NO_EVENT_TEXT: Readonly<Record<string, string>> = {
  Sound: 'Sound dispatches no soundComplete event: a game that waits for it keeps waiting',
  SoundChannel: 'SoundChannel dispatches no soundComplete event: a game that waits for it keeps waiting',
  URLLoader: 'URLLoader dispatches no complete, ioError or progress event: a game that waits for one keeps waiting',
  Loader: 'Loader dispatches no complete, ioError or progress event: a game that waits for one keeps waiting',
  LocalConnection: 'LocalConnection delivers no message and dispatches no event: a game that waits for one keeps waiting',
};

export function simpleName(qualified: string): string {
  const at = qualified.lastIndexOf('.');
  return at < 0 ? qualified : qualified.slice(at + 1);
}

/** Non-stub classes a stub signature may name, with the Shim module that holds them. */
const SHIM_TYPES: Readonly<Record<string, string>> = { DisplayObject: '../DisplayObject', EventDispatcher: '../events' };

function stubNames(): ReadonlySet<string> {
  return new Set(FLASH_API_TABLE.filter((e) => e.policy === 'stub').map((e) => simpleName(e.qualified)));
}

function lit(n: Neutral): string {
  if (n === null) return 'null';
  if (typeof n === 'string') return JSON.stringify(n);
  if (typeof n === 'object' && !Array.isArray(n) && 'stubObject' in n) throw new Error('lit: a stubObject has no literal');
  if (Array.isArray(n)) return '[]';
  return String(n);
}

function isStubObject(n: Neutral): n is { readonly stubObject: string } {
  return typeof n === 'object' && n !== null && !Array.isArray(n) && 'stubObject' in n;
}

/** The TypeScript type of an AS3 type name; `uses` collects the class names the text refers to. */
function tsType(as3: string, nullable: boolean, stubs: ReadonlySet<string>, uses: Set<string>): string {
  let t: string;
  switch (as3) {
    case 'Number': case 'int': case 'uint': t = 'number'; break;
    case 'String': t = 'string'; break;
    case 'Boolean': t = 'boolean'; break;
    case 'void': return 'void';
    case '*': case 'Object': return 'any';
    case 'Function': t = '(...args: any[]) => any'; break;
    default:
      if (stubs.has(as3) || as3 in SHIM_TYPES) {
        uses.add(as3);
        t = as3;
      } else return 'any';
  }
  return nullable ? `${t} | null` : t;
}

function renderParam(p: ParamSig, stubs: ReadonlySet<string>, uses: Set<string>): string {
  const [name, type, def] = p;
  if (name.startsWith('...')) return `${name}: any[]`;
  const t = tsType(type, def === 'null', stubs, uses);
  return def === undefined ? `${name}: ${t}` : `${name}: ${t} = ${def}`;
}

function renderParams(ps: readonly ParamSig[], stubs: ReadonlySet<string>, uses: Set<string>): string {
  return ps.map((p) => renderParam(p, stubs, uses)).join(', ');
}

interface Ctx {
  cls: string;
  entry: FlashApiEntry;
  stubs: ReadonlySet<string>;
  uses: Set<string>;
  values: Set<string>;
}

function returnExpr(c: Ctx, m: MemberSig, id: string): string {
  const n = m.neutral;
  if (isStubObject(n)) {
    const target = n.stubObject;
    const owner = m.static ? c.cls : 'this';
    const make = target === 'Object' ? '() => ({})' : `() => new ${target}()`;
    if (target !== 'Object') c.values.add(target);
    let key = JSON.stringify(m.name);
    if (m.static && m.params.length > 0 && !m.params[0]![0].startsWith('...')) {
      key = `${JSON.stringify(`${m.name}:`)} + String(${m.params[0]![0]})`;
    }
    return `stubCall(${JSON.stringify(id)}, stubInstance(${owner}, ${key}, ${make}))`;
  }
  return `stubCall(${JSON.stringify(id)}, ${lit(n)})`;
}

function noEventLine(c: Ctx): string {
  if (c.entry.canStall !== true) return '';
  const text = NO_EVENT_TEXT[c.cls] ?? `${c.cls} dispatches no completion event: a game that waits for one keeps waiting`;
  return `    stubNoEvent(${JSON.stringify(c.cls)}, ${JSON.stringify(text)});\n`;
}

function renderMember(c: Ctx, m: MemberSig): string {
  const id = `${c.cls}.${m.name}`;
  const st = m.static ? 'static ' : '';
  const stObjType = isStubObject(m.neutral) ? (m.neutral.stubObject === 'Object' ? 'any' : m.neutral.stubObject) : null;
  const retType = (): string => {
    if (stObjType !== null) {
      if (stObjType !== 'any') c.uses.add(stObjType);
      return stObjType;
    }
    return tsType(m.returns, m.neutral === null && m.returns !== 'void', c.stubs, c.uses);
  };
  switch (m.kind) {
    case 'field': {
      const t = tsType(m.returns, m.neutral === null, c.stubs, c.uses);
      return `  ${st}${m.name}: ${t} = ${lit(m.neutral)};\n`;
    }
    case 'getter':
      return `  ${st}get ${m.name}(): ${retType()} {\n${noEventLine(c)}    return ${returnExpr(c, m, id)};\n  }\n`;
    case 'setter':
      return `  ${st}set ${m.name}(${renderParams(m.params, c.stubs, c.uses)}) {\n${noEventLine(c)}    stubCall(${JSON.stringify(id)}, null);\n  }\n`;
    case 'method': {
      const body = m.returns === 'void' ? `    stubCall(${JSON.stringify(id)}, null);\n` : `    return ${returnExpr(c, m, id)};\n`;
      return `  ${st}${m.name}(${renderParams(m.params, c.stubs, c.uses)}): ${retType()} {\n${noEventLine(c)}${body}  }\n`;
    }
    case 'constructor':
      throw new Error('renderMember: constructor is rendered by renderConstructor');
  }
}

function renderConstructor(c: Ctx, ctor: MemberSig | undefined): string {
  const params = ctor?.params ?? [];
  const head = `  constructor(${renderParams(params, c.stubs, c.uses)}) {\n`;
  const sup = c.entry.extends !== undefined ? '    super();\n' : '';
  const note = `    stubConstructed(${JSON.stringify(c.cls)}, ${c.entry.canStall === true ? 'true' : 'false'}, ${JSON.stringify(
    c.entry.canStall === true ? (NO_EVENT_TEXT[c.cls] ?? `${c.cls} dispatches no completion event: a game that waits for one keeps waiting`) : '',
  )});\n`;
  // A constructor parameter that has the name and type of a field stores into it (URLRequest keeps its url).
  let keep = '';
  for (const p of params) {
    const f = c.entry.members?.find((m) => m.kind === 'field' && m.name === p[0] && !m.static && m.returns === p[1]);
    if (f !== undefined) keep += `    if (${p[0]} !== null) this.${p[0]} = ${p[0]};\n`;
  }
  for (const [param, fieldName] of ctor?.stores ?? []) {
    const p = params.find((x) => x[0] === param);
    keep += p?.[2] === 'null' ? `    if (${param} !== null) this.${fieldName} = ${param};\n` : `    this.${fieldName} = ${param};\n`;
  }
  return `${head}${sup}${note}${keep}  }\n`;
}

/** Renders one `stub` entry. `navigateToURL` becomes an exported function: it is not a class in Flash. */
export function renderStub(entry: FlashApiEntry): RenderedStub {
  const stubs = stubNames();
  const cls = simpleName(entry.qualified);
  const c: Ctx = { cls, entry, stubs, uses: new Set(), values: new Set() };
  const members = entry.members ?? [];
  let body: string;
  const helpers = new Set<string>(['stubCall']);

  if (cls === 'navigateToURL') {
    const m = members[0]!;
    body = `export function navigateToURL(${renderParams(m.params, stubs, c.uses)}): void {\n  stubCall(${JSON.stringify('navigateToURL')}, null);\n}\n`;
  } else {
    const ctor = members.find((m) => m.kind === 'constructor');
    const fields = members.filter((m) => m.kind === 'field').map((m) => renderMember(c, m));
    const rest = members.filter((m) => m.kind !== 'constructor' && m.kind !== 'field').map((m) => renderMember(c, m));
    const ctorText = renderConstructor(c, ctor);
    const ext = entry.extends !== undefined ? ` extends ${entry.extends}` : '';
    if (entry.extends !== undefined) c.uses.add(entry.extends);
    body = `export class ${cls}${ext} {\n${[...fields, ctorText, ...rest].join('\n')}}\n`;
    helpers.add('stubConstructed');
    if (entry.canStall === true) helpers.add('stubNoEvent');
  }
  if (body.includes('stubInstance(')) helpers.add('stubInstance');
  if (body.includes('stubNoEvent(')) helpers.add('stubNoEvent');

  const lines: string[] = [STUB_HEADER, `import { ${[...helpers].sort().join(', ')} } from '../stubSupport';`];
  const own = new Set([cls]);
  for (const v of [...c.values].sort()) if (!own.has(v)) lines.push(`import { ${v} } from './${v}';`);
  for (const u of [...c.uses].sort()) {
    if (own.has(u) || c.values.has(u)) continue;
    if (u in SHIM_TYPES) lines.push(`import ${u === 'EventDispatcher' ? '' : 'type '}{ ${u} } from '${SHIM_TYPES[u]}';`);
    else lines.push(`import type { ${u} } from './${u}';`);
  }
  return { name: cls, file: `${cls}.ts`, text: `${lines.join('\n')}\n\n${body}` };
}

/** Every `stub` entry, in table order. A class is generated if and only if its policy is `stub`. */
export function renderAllStubs(): RenderedStub[] {
  return FLASH_API_TABLE.filter((e) => e.policy === 'stub').map(renderStub);
}
